class StudentData {
  final String name;
  final String email;
  final String usn;
  final String department;
  final int semester;
  final int attendancePercentage;
  final int performancePercentage;

  const StudentData({
    required this.name,
    required this.email,
    required this.usn,
    required this.department,
    required this.semester,
    required this.attendancePercentage,
    required this.performancePercentage,
  });
}